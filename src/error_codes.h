/**
 * ============================================================================
 *  error_codes.h - 错误码定义
 *  PPTX 智能打开器
 * ============================================================================
 *  统一的错误码体系，用于模块间传递执行结果。
 *  注意：本程序在多数失败路径下会兜底启动，错误码主要用于日志与诊断。
 * ============================================================================
 */
#pragma once

namespace pptx_selector {

enum class Err {
    Ok              = 0,  ///< 成功
    InvalidArgs     = 1,  ///< 命令行参数不足
    FileNotFound    = 2,  ///< 目标 PPTX 文件不存在
    ReadFailed      = 3,  ///< 文件读取失败
    InvalidArchive  = 4,  ///< ZIP 解析失败
    LaunchFailed    = 5,  ///< 启动外部程序失败
    NoLauncher      = 6,  ///< 未找到任何可用启动器
};

}  // namespace pptx_selector
